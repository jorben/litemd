// 生成随应用打包的第三方许可声明 frontend/public/THIRD_PARTY_NOTICES.txt（make notices）。
// 内容：THIRD_PARTY.md 原文（含 vmark 的 ISC 全文）、链接进应用的 Go 模块与 Go 标准库的许可文件、
// 打进前端的 npm 生产依赖（pnpm licenses list --prod）的许可文件。相同的许可全文合并为一节。
// 输出不含绝对路径和时间戳，同一份锁文件与 go.mod 重复生成结果不变。只用 Node 内置模块。
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const out = join(root, "frontend/public/THIRD_PARTY_NOTICES.txt");
// 应用支持的平台；Go 依赖按平台取并集（例如 golang.org/x/net 只在 Windows 版链接）
const GOOS = ["darwin", "windows", "linux"];

const run = (cmd, args, env = {}) =>
  execFileSync(cmd, args, { cwd: root, encoding: "utf8", maxBuffer: 64 << 20, env: { ...process.env, ...env } });
const clean = (s) => s.replace(/\r\n?/g, "\n").replace(/^\uFEFF/, "").trim();

// 包目录里的许可文件：LICENSE、LICENCE、COPYING、NOTICE、PATENTS、MIT-License.txt、LICENSE-MPL 等
const LICENSE_FILE = /(^|[-_.])(licen[cs]e|copying|notice|patents|unlicense)([-_.]|$)/i;
const TEXT_EXT = /^[^.]*(\.(md|txt|markdown))?$/i;
function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f) && TEXT_EXT.test(f))
    .sort()
    .map((f) => clean(readFileSync(join(dir, f), "utf8")));
}

// ── Go：链接进应用的模块（各平台并集） ──
function goModules() {
  const mods = new Map();
  for (const goos of GOOS) {
    const lines = run("go", ["list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}", "."], {
      GOOS: goos,
      CGO_ENABLED: "1",
    });
    for (const line of lines.split("\n").filter(Boolean)) {
      const [path, version, dir] = line.split(" ");
      mods.set(`${path}@${version}`, { name: path, version, dir });
    }
  }
  const goroot = run("go", ["env", "GOROOT"]).trim();
  const list = [...mods.values()].sort((a, b) => a.name.localeCompare(b.name));
  return [
    { label: "Go standard library and runtime", texts: [clean(readFileSync(join(goroot, "LICENSE"), "utf8"))] },
    ...list.map((m) => ({ label: `${m.name} ${m.version}`, texts: licenseFiles(m.dir) })),
  ];
}

// ── npm：打进前端的生产依赖 ──
function npmPackages() {
  const byLicense = JSON.parse(run("pnpm", ["-C", "frontend", "licenses", "list", "--prod", "--json"]));
  const pkgs = [];
  for (const [license, entries] of Object.entries(byLicense)) {
    for (const p of entries) {
      p.versions.forEach((version, i) => {
        const texts = licenseFiles(p.paths[i]);
        const label = `${p.name} ${version}`;
        if (texts.length) pkgs.push({ label, texts });
        else {
          // 包内没有许可文件：照录 package.json 声明的许可、作者与主页
          const meta = [`License (declared in package.json): ${license}`];
          if (p.author) meta.push(`Author: ${p.author}`);
          if (p.homepage) meta.push(`Homepage: ${p.homepage}`);
          pkgs.push({ label, texts: [`The package ships no license file.\n${meta.join("\n")}`] });
        }
      });
    }
  }
  return pkgs.sort((a, b) => a.label.localeCompare(b.label));
}

// 许可全文相同的包合并为一节，按第一个包名排序
function section(title, items) {
  const groups = new Map();
  for (const it of items) {
    const key = it.texts.join("\n\n-----\n\n");
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(it.label);
  }
  const rule = "-".repeat(78);
  const body = [...groups.entries()].map(([text, labels]) => `${rule}\n${labels.join("\n")}\n${rule}\n\n${text}\n`);
  return `${"=".repeat(78)}\n${title}\n${"=".repeat(78)}\n\n${body.join("\n")}`;
}

const go = goModules();
const npm = npmPackages();
const doc = [
  "LiteMd — Third-Party Notices",
  "",
  "LiteMd is licensed under the Apache License 2.0. It includes the third-party",
  "software listed below; each component's license text follows its name.",
  "Generated by `make notices` (scripts/third-party-notices.mjs). Do not edit.",
  "",
  section("THIRD_PARTY.md (migrated code: vmark, ISC)", [{ label: "THIRD_PARTY.md", texts: [clean(readFileSync(join(root, "THIRD_PARTY.md"), "utf8"))] }]),
  section(`Go modules linked into the app (${go.length - 1} modules + Go runtime)`, go),
  section(`npm packages bundled into the frontend (${npm.length} packages)`, npm),
].join("\n");

writeFileSync(out, doc);
console.log(`wrote ${out.slice(root.length + 1)}: ${go.length - 1} Go modules, ${npm.length} npm packages, ${Buffer.byteLength(doc)} bytes`);
